    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        String u = txtName.getText().trim();
        String p = new String(txtPassword.getPassword()).trim();
        String r = (String) cmbRole.getSelectedItem();

        if (u.isEmpty() || p.isEmpty() || r.equals("Select Role")) {
            JOptionPane.showMessageDialog(this, "Fill required fields");
            return;
        }

        User user = new User(u, p, r);
        boolean ok = controller.createUser(user);
        if (ok) {
            JOptionPane.showMessageDialog(this, "User created");
            txtName.setText(""); txtPassword.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Create failed (maybe username exists)");
    }//GEN-LAST:event_btnCreateActionPerformed
    }
    
