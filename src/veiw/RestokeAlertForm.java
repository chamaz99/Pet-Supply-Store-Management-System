     private void loadLowStockData() throws SQLException {
          DefaultTableModel model = (DefaultTableModel) tblRestoke.getModel(); 
          model.setRowCount(0);
          
          try{
               Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/petcare", "root", "");
               String sql = "SELECT * FROM store WHERE quntity < 20"; 
            Statement st = con.createStatement();
            ResultSet rs = (ResultSet) st.executeQuery(sql);

            while (rs.next()) {
                String code = rs.getString("itemcode");
                String name = rs.getString("name");
                int qty = rs.getInt("quntity");
                
                model.addRow(new Object[]{code, name, qty});
          }
           } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
     }
    
    
