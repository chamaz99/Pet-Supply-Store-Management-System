    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        try {  
        int id = Integer.parseInt(txtitemcode.getText());
        PetcareController controller = new PetcareController();
        controller.deleteItem(id);
        JOptionPane.showMessageDialog(this, "Delete item is Sucssesful !!");
        loaddata();
        txtitemcode.setText("");
        }catch(HeadlessException | NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
 }
    }//GEN-LAST:event_btndeleteActionPerformed

    private void btnlogoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnlogoutActionPerformed
        int response = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to logout?", "Logout", 
            javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (response == javax.swing.JOptionPane.YES_OPTION) {
        this.dispose(); 
       
        new Petview().setVisible(true); 
    }
    }//GEN-LAST:event_btnlogoutActionPerformed

    private void loaddata() {
    
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0); // clear existing rows
        List<petcare> list = controller.getitem();
        for (petcare p : list) {
            model.addRow(new Object[]{p.getcode(),p.getName(),p.getquntity(),p.getUnitPrice()});
    
    }
    }
    
  
  
