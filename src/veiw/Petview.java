    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String username = txtUsername.getText();
    String password = new String(txtPassword.getPassword());
    String userRole = "";
    
    if (rbPetAssistant.isSelected()) {
        userRole = "Pet Assistant";
    } else if (rbStoreManager.isSelected()) {
        userRole = "Store Manager";
    }
    
    if (userRole.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select your Role (Store Manager/Pet Assistant) ", " Warning!", JOptionPane.WARNING_MESSAGE);
    } else {
        boolean loginSuccess = false;
        // --- Store Manager Login ---
        if (userRole.equals("Store Manager") && username.equals("admin") && password.equals("123")) {
            loginSuccess = true;
            
            // Store Manager Form 
            NewStoreManagerForm smForm = new NewStoreManagerForm(); 
            smForm.setVisible(true);
            
            // --- Pet Assistant Login ---
        } else if (userRole.equals("Pet Assistant") && username.equals("pet") && password.equals("123")) {
            loginSuccess = true;
            
            // Pet Assistant Form 
            NewPetAssistantForm paForm = new NewPetAssistantForm();
            paForm.setVisible(true);
    }//GEN-LAST:event_jButton1ActionPerformed
     
       
        if (loginSuccess) {
            JOptionPane.showMessageDialog(this, userRole + " login Succsessful "+".", "Succsess", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); 
        } else {
           
            JOptionPane.showMessageDialog(this, "LOGIN UNSUCSESSFUL!!! ", " Warning!   ", JOptionPane.ERROR_MESSAGE);
            txtPassword.setText("");
        }
    }                                        
    }
    
